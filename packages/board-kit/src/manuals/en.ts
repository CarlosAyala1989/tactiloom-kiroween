import { catalogRows, exampleRows, type ManualContext } from './shared';

export function manualEn(context: ManualContext): string {
  const { entries, template, titles, branch } = context;
  const { grid, card } = template;
  return `# Tactiloom — Printing and assembly manual for the kit (board-v1 / cards-v1)

> Generated by \`pnpm board:generate\`. Do not edit by hand.

## 1. What to print

| File | Use |
|---|---|
| \`board-v1-a3.pdf\` | Full board on **A3 landscape** (recommended). |
| \`board-v1-a4-tiles.pdf\` | The same board on **4 A4 landscape sheets** at full scale. |
| \`board-v1-small-a4.pdf\` | **Reduced** board (scale 0.707) on a single A4 sheet, for quick tests. |
| \`cards-v1-a4.pdf\` | ${entries.length} full-scale cards (${card.width} × ${card.height} mm) for the A3 board or the tiles. |
| \`cards-v1-small-a4.pdf\` | The same cards, reduced, for the reduced A4 board. |

**Always print at 100%** (“actual size”, never “fit to page”). Check the verification bar on the board: it must
measure 100 mm (70.7 mm on the reduced version). Matte white paper reduces glare.

## 2. Assembly

1. **A3:** nothing to assemble. Glue the board onto cardboard or tape its edges to the table.
2. **A4 tiles:** trim each sheet at its crop marks (corners) and join the 4 sheets **edge to edge**
   in the order 1-2 (top) and 3-4 (bottom), with tape on the back. A misalignment of 1–2 mm is acceptable because
   calibration uses the 4 corner markers, but keep the sheet flat.
3. **Cards:** cut along the rounded grey border. Do not cut or fold the marker or its white margin.
   Optional: glue each card onto thin card so that it does not curl.

## 3. Placement rules (Tactiloom Board Grammar v1)

- A grid of **8 columns × 4 rows**; cells of ${grid.cellWidth} × ${grid.cellHeight} mm. The coordinates printed
  in each cell are \`row,column\` (counting from 0).
- One card per cell, centred. The **4 corner markers (ID 0, 1, 2, 3)** must be fully visible in the photo.
- The **printed arrow** on a card is its forward direction **F**. When the card is upright (title at the top),
  F points **east**. Rotate the card in steps of 90° to change F.
- Each card receives the workflow through its rear edge (**IN**, opposite F) and passes it on to the neighbouring cell in F (**OUT**).
- **${titles.CONDITION}:** the **${branch.TRUE}** output goes along F; the **${branch.FALSE}** output turns 90° to the right of F (the printed “${branch.FALSE}” arrow).
  The two outputs must lead to different cards.
- **${titles.END}** has no output. Every path must finish on an ${titles.END} card.
- Empty cells do **not** connect cards: connections only exist between adjacent cells.

### Two-branch example (official fixture)

| Card | Cell (row,col) | Orientation |
|---|---|---|
${exampleRows(context, { branches: `${branch.TRUE} → east, ${branch.FALSE} → south`, rotated: 'rotated 90° clockwise' })}

## 4. Taking the photo

- Hold the camera as square to the board as you can, with the whole board in the frame and soft light without hard shadows.
- Recommended minimum resolution: 1280 × 720. Avoid glare on the markers.
- Moving a card **never** runs anything: you have to analyse, compile, review and approve again.

## 5. Printed catalogue (cards-v1)

| Marker | Kind | Printed title | Instance | Set |
|---|---|---|---|---|
${catalogRows(context)}

IDs 0–3 are reserved for the corners; 36–89 are reserved for future cards and are rejected as
\`UNKNOWN_CARD\`. Dictionary: \`${template.dictionary}\`.
`;
}

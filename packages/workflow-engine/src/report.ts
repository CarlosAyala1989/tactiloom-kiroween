/** Escapes Markdown/HTML-significant characters so extracted values render as plain text. */
export function escapeMarkdown(value: string): string {
  return value
    // eslint-disable-next-line no-control-regex -- intentionally strips control characters from untrusted text
    .replace(/[\u0000-\u001f\u007f]/g, ' ')
    .replace(/[\\`*_{}[\]()#+\-.!|<>~=&"']/g, (char) => `\\${char}`);
}

function fieldStatus(validation: ValidationResult, field: FieldId, strings: ReportStrings): string {
  if (!validation.requiredFields.includes(field)) return validation.fields[field] === null ? strings.status.notRequired : strings.status.presentNotRequired;
  if (validation.missingFields.includes(field)) return strings.status.missing;
  if (validation.invalidFields.includes(field)) return strings.status.invalid;
  return strings.status.ok;
}

/** workshop-summary-v1: Markdown (localized) and/or JSON (language-neutral keys) built only from extracted data. */
export function renderReport(input: ReportInput): RenderedReport {
  const { validation } = input;
  const language = input.language ?? 'es';
  const s = REPORT_STRINGS[language];
  const generatedAt = input.generatedAt.toISOString();
  const markdown =
    input.format === 'json'
      ? null
      : [
          `# ${s.title}`,
          '',
          `- **${s.run}:** \`${input.runId}\``,
          `- **${s.node}:** \`${input.nodeId}\``,
          `- **${s.generated}:** ${generatedAt}`,
          `- **${s.document}:** ${escapeMarkdown(input.document.originalName)} (sha256 \`${input.document.sha256.slice(0, 16)}…\`)`,
          `- **${s.extraction}:** ${s.extractionDetail(input.extraction.method, input.extraction.pages, input.extraction.chars)}`,
          `- **${s.result}:** ${validation.isValid ? s.valid : s.incomplete}`,
          '',
          `| ${s.columns.join(' | ')} |`,
          '|---|---|---|',
          ...FIELD_IDS.map((field) => {
            const value = validation.fields[field];
            return `| ${s.fields[field]} | ${value === null ? '—' : escapeMarkdown(value)} | ${fieldStatus(validation, field, s)} |`;
          }),
          '',
          `> ${s.footer}`,
          '',
        ].join('\n');
  const json =
    input.format === 'markdown'
      ? null
      : `${JSON.stringify(
          {
            reportVersion: 'workshop-summary-v1',
            language,
            runId: input.runId,
            nodeId: input.nodeId,
            generatedAt,
            document: input.document,
            extraction: input.extraction,
            fields: validation.fields,
            requiredFields: validation.requiredFields,
            missingFields: validation.missingFields,
            invalidFields: validation.invalidFields,
            isValid: validation.isValid,
          },
          null,
          2,
        )}\n`;
  return { markdown, json };
}
